const { contextBridge, ipcRenderer, webUtils } = require('electron');

const invoke = (ch, ...a) => ipcRenderer.invoke(ch, ...a);
const on = ch => cb => {
  const h = (_e, d) => cb(d);
  ipcRenderer.on(ch, h);
  return () => ipcRenderer.removeListener(ch, h);
};

contextBridge.exposeInMainWorld('lab', {
  login: () => invoke('auth:login'),
  restore: () => invoke('auth:restore'),
  logout: () => invoke('auth:logout'),
  getSettings: () => invoke('store:get'),
  setSettings: p => invoke('store:set', p),
  openExternal: url => invoke('open:external', url),
  openFolder: id => invoke('open:folder', id),
  versions: snaps => invoke('versions:list', snaps),
  loaders: v => invoke('loaders:supported', v),
  listInstances: () => invoke('instances:list'),
  createInstance: d => invoke('instances:create', d),
  getInstance: id => invoke('instances:get', id),
  deleteInstance: id => invoke('instances:delete', id),
  searchMods: q => invoke('mods:search', q),
  installMod: d => invoke('mods:install', d),
  removeMod: d => invoke('mods:remove', d),
  isOnline: () => invoke('net:online'),
  prefetchMods: q => invoke('mods:prefetch', q),
  social: {
    me: () => invoke('social:me'),
    prove: id => invoke('social:prove', id),
    verify: d => invoke('social:verify', d),
    lookup: n => invoke('social:lookup', n),
    load: () => invoke('social:load'),
    save: d => invoke('social:save', d),
  },
  checkUpdate: () => invoke('update:check'),
  installUpdate: () => invoke('update:install'),
  onUpdateProgress: on('update:progress'),
  addModFiles: d => invoke('mods:addFiles', d),
  joinServer: d => invoke('game:join', d),
  servers: {
    info: () => invoke('servers:info'),
    list: () => invoke('servers:list'),
    log: id => invoke('servers:log', id),
    create: d => invoke('servers:create', d),
    update: d => invoke('servers:update', d),
    remove: id => invoke('servers:delete', id),
    folder: id => invoke('servers:folder', id),
    start: id => invoke('servers:start', id),
    stop: id => invoke('servers:stop', id),
    command: d => invoke('servers:command', d),
    onStatus: on('server:status'),
    onLog: on('server:log'),
  },
  maker: {
    list: () => invoke('maker:list'),
    save: m => invoke('maker:save', m),
    remove: uid => invoke('maker:delete', uid),
    preview: d => invoke('maker:preview', d),
    install: d => invoke('maker:install', d),
    exportJar: d => invoke('maker:export', d),
  },
  filePath: f => webUtils.getPathForFile(f),
  speedBoost: id => invoke('speed:boost', id),
  onSpeedProgress: on('speed:progress'),
  installModpack: d => invoke('modpack:install', d),
  importModpack: () => invoke('modpack:importFile'),
  onModpackProgress: on('modpack:progress'),
  publish: {
    prepare: d => invoke('publish:prepare', d),
    save: f => invoke('publish:save', f),
    token: t => invoke('publish:token', t),
    modrinth: d => invoke('publish:modrinth', d),
  },
  launch: id => invoke('game:launch', id),
  stop: id => invoke('game:stop', id),
  onModProgress: on('mods:progress'),
  onLaunchStatus: on('launch:status'),
  onLaunchLog: on('launch:log'),
  onLaunchClosed: on('launch:closed'),
});
